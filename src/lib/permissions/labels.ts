/** Permissions grouped for the roles editor. */
export function permissionGroups(
  keys: PermissionKey[],
  isScoped: (key: PermissionKey) => boolean,
): { title: string; permissions: { key: PermissionKey; label: string; scoped: boolean }[] }[] {
  return GROUPS.map((group) => ({
    title: group.title,
    permissions: keys
      .filter((key) => group.families.includes(key.split('.')[0] ?? ''))
      .map((key) => ({ key, label: PERMISSION_LABELS[key], scoped: isScoped(key) })),
  })).filter((group) => group.permissions.length > 0);
}
